export const MOVIES: Movie[] = RAW;

export const ALL_GENRES: string[] = Array.from(
  new Set(MOVIES.flatMap((movie) => movie.genres)),
).sort((a, b) => a.localeCompare(b, "ru"));

export function getMovieById(id: string): Movie | undefined {
  return MOVIES.find((movie) => movie.id === id);
}

export function getYearBounds(): { min: number; max: number } {
  const years = MOVIES.map((movie) => movie.year).filter(
    (year) => typeof year === "number",
  );
  return { min: Math.min(...years), max: Math.max(...years) };
}

/** Единый источник постера: либо TMDB, либо локальная генерация. */
export function posterUrl(posterPath: string | null | undefined, size = "w500"): string | null {
  if (!posterPath) return null;
  if (/^https?:\/\//.test(posterPath)) return posterPath;
  const clean = posterPath.replace(/^\//, "");
  return `https://image.tmdb.org/t/p/${size}/${clean}`;
}
